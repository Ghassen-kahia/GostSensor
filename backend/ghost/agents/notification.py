"""Agent 4 - alerting and notification.

Delivery truthfulness:
* EMAIL_MODE=test writes an .eml file to the outbox; status is TEST_MODE, never SENT.
* EMAIL_MODE=smtp marks SENT only when the SMTP server accepted the message for
  every recipient (smtplib returned without refusals). Anything else is FAILED
  or PENDING (retry with exponential backoff, bounded attempts).
"""
from __future__ import annotations

import html
import smtplib
import socket
import ssl
from email.message import EmailMessage
from email.utils import make_msgid

from .. import db
from ..config import load_policy, settings
from ..engine import clock
from ..engine import incidents as inc_store
from .documentation import _advance, iso
from .runs import Trigger, agent_run

PERMANENT_ERRORS = (smtplib.SMTPAuthenticationError, smtplib.SMTPRecipientsRefused, smtplib.SMTPSenderRefused)


def email_config_status() -> dict:
    missing = []
    if settings.email_mode == "smtp":
        for name, val in (("SMTP_HOST", settings.smtp_host), ("EMAIL_FROM", settings.email_from)):
            if not val:
                missing.append(name)
    if not settings.alert_recipients:
        missing.append("ALERT_RECIPIENTS")
    return {"mode": settings.email_mode, "configured": not missing, "missing": missing,
            "recipients": len(settings.alert_recipients), "escalationRecipients": len(settings.escalation_recipients),
            "smtpHost": settings.smtp_host if settings.email_mode == "smtp" else None}


def _latest(conn, table: str, iid: str) -> dict | None:
    return db.row(f"SELECT * FROM {table} WHERE incident_id=? ORDER BY version DESC LIMIT 1", (iid,), conn)


def compose(conn, inc: dict, kind: str) -> tuple[str, str, str]:
    """Subject, plain text and HTML built only from stored, validated data."""
    report = _latest(conn, "incident_reports", inc["id"])
    analysis = _latest(conn, "analyses", inc["id"])
    hyps = db.rows("SELECT title, support FROM hypotheses WHERE analysis_id=? ORDER BY rank LIMIT 3", (analysis["id"],), conn) if analysis else []
    recs = db.rows("SELECT action, urgency FROM recommendations WHERE analysis_id=? ORDER BY rank LIMIT 4", (analysis["id"],), conn) if analysis else []
    preds = db.rows("""SELECT sensor_id, value, lower, upper, quality, target_ts FROM virtual_predictions WHERE incident_id=? AND value IS NOT NULL
                       AND id IN (SELECT MAX(id) FROM virtual_predictions WHERE incident_id=? GROUP BY sensor_id) LIMIT 5""", (inc["id"], inc["id"]), conn)
    n_sensors = db.scalar("SELECT COUNT(*) FROM incident_sensors WHERE incident_id=?", (inc["id"],), conn)
    tag = {"ALERT": "ALERT", "ESCALATION": "ESCALATION", "ACKNOWLEDGED": "ACKNOWLEDGED", "RESOLVED": "RESOLVED"}[kind]
    prefix = "[SIMULATED] " if inc["simulated"] else ""
    subject = f"{prefix}[Ghost Sensor][{inc['severity']}][{tag}] {inc['id']} - {inc['title']}"[:200]
    link = f"{settings.dashboard_url.rstrip('/')}/incidents/{inc['id']}"
    mode = clock.state(conn).mode
    lines = [
        f"Incident {inc['id']} - {tag}",
        f"Severity: {inc['severity']}   Category: {inc['category']}   Status: {inc['status']}",
        f"Room: {inc['primary_room_id'] or '-'}   Sensor: {inc['primary_sensor_id'] or '-'}   Sensors involved: {n_sensors}",
        f"Detected (building time): {iso(inc['detected_ts'])}" + ("   [replay of historical data]" if mode == "REPLAY" else ""),
        "",
        "Observed problem:",
        f"  {(report['summary'] if report else inc['summary']) or inc['title']}",
    ]
    if kind == "RESOLVED":
        lines += ["", f"Resolution: {inc['resolution_note'] or '-'} (by {inc['resolved_by']})"]
    if kind == "ACKNOWLEDGED":
        lines += ["", f"Acknowledged by {inc['acknowledged_by']}."]
    if preds:
        lines += ["", "Inferred values (virtual sensor - NOT physical measurements):"]
        lines += [f"  {p['sensor_id']}: {p['value']:.2f} [{p['lower']:.2f}, {p['upper']:.2f}] 90% interval, quality {p['quality']}" for p in preds]
    if hyps:
        lines += ["", "Suspected causes (automated hypotheses, unconfirmed):"]
        lines += [f"  - {h['title']} [{h['support']} rule support]" for h in hyps]
    if recs:
        lines += ["", "Recommended next steps (advisory - nothing has been done automatically):"]
        lines += [f"  - [{r['urgency']}] {r['action']}" for r in recs]
    lines += ["", f"Dashboard: {link}", "", "Generated by Ghost Sensor Agent 4. Do not reply."]
    text = "\n".join(lines)
    body = "".join(f"<p>{html.escape(l)}</p>" if l else "<br>" for l in lines[:-3])
    color = {"CRITICAL": "#b42318", "HIGH": "#c4320a", "MEDIUM": "#b54708", "LOW": "#175cd3", "INFO": "#475467"}[inc["severity"]]
    html_body = (f"<div style='font-family:Segoe UI,Arial,sans-serif;font-size:14px;color:#101828'>"
                 f"<div style='border-left:4px solid {color};padding-left:12px'>{body}</div>"
                 f"<p><a href='{html.escape(link)}'>Open incident in the dashboard</a></p>"
                 f"<p style='color:#667085;font-size:12px'>Generated by Ghost Sensor Agent 4. Inferred values are not physical measurements.</p></div>")
    return subject, text, html_body


def _deliver(conn, notif: dict, subject: str, text: str, html_body: str, recipients: list[str]) -> None:
    msg = EmailMessage()
    msg["Subject"] = subject
    msg["From"] = settings.email_from or "ghost-sensor@localhost"
    msg["To"] = ", ".join(recipients)
    msg["Message-ID"] = make_msgid(domain="ghost-sensor.local")
    msg.set_content(text)
    msg.add_alternative(html_body, subtype="html")
    attempt = notif["attempts"] + 1
    now = db.now_real()
    pol = load_policy("notification")["retry"]
    if settings.email_mode != "smtp":
        settings.outbox_dir.mkdir(parents=True, exist_ok=True)
        path = settings.outbox_dir / f"{notif['id']:06d}-{notif['incident_id']}-{notif['kind']}.eml"
        path.write_bytes(bytes(msg))
        db.execute("UPDATE notifications SET status='TEST_MODE', status_reason=?, attempts=?, artifact_path=?, sent_real=NULL, next_attempt_real=NULL WHERE id=?",
                   ("EMAIL_MODE=test: written to outbox, not sent", attempt, str(path), notif["id"]), conn)
        db.execute("INSERT INTO notification_attempts(notification_id,attempt_no,at_real,success,provider_response) VALUES (?,?,?,1,?)",
                   (notif["id"], attempt, now, "test mode: .eml written"), conn)
        return
    try:
        if settings.smtp_ssl:
            server = smtplib.SMTP_SSL(settings.smtp_host, settings.smtp_port, timeout=20, context=ssl.create_default_context())
        else:
            server = smtplib.SMTP(settings.smtp_host, settings.smtp_port, timeout=20)
        with server:
            if settings.smtp_starttls and not settings.smtp_ssl:
                server.starttls(context=ssl.create_default_context())
            if settings.smtp_user:
                server.login(settings.smtp_user, settings.smtp_password or "")
            refused = server.send_message(msg)
        if refused:
            raise smtplib.SMTPRecipientsRefused(refused)
        db.execute("UPDATE notifications SET status='SENT', status_reason='accepted by SMTP server', attempts=?, sent_real=?, next_attempt_real=NULL, last_error=NULL, provider_response=? WHERE id=?",
                   (attempt, now, f"accepted for {len(recipients)} recipient(s); Message-ID {msg['Message-ID']}", notif["id"]), conn)
        db.execute("INSERT INTO notification_attempts(notification_id,attempt_no,at_real,success,provider_response) VALUES (?,?,?,1,?)",
                   (notif["id"], attempt, now, "250 accepted"), conn)
    except PERMANENT_ERRORS as exc:
        err = f"{type(exc).__name__}: {str(exc)[:300]}"
        db.execute("UPDATE notifications SET status='FAILED', status_reason='permanent SMTP error', attempts=?, last_error=?, next_attempt_real=NULL WHERE id=?",
                   (attempt, err, notif["id"]), conn)
        db.execute("INSERT INTO notification_attempts(notification_id,attempt_no,at_real,success,error) VALUES (?,?,?,0,?)", (notif["id"], attempt, now, err), conn)
    except (smtplib.SMTPException, OSError, socket.timeout) as exc:
        err = f"{type(exc).__name__}: {str(exc)[:300]}"
        if attempt >= pol["max_attempts"]:
            db.execute("UPDATE notifications SET status='FAILED', status_reason=?, attempts=?, last_error=?, next_attempt_real=NULL WHERE id=?",
                       (f"gave up after {attempt} attempts", attempt, err, notif["id"]), conn)
        else:
            delay = min(pol["base_delay_s"] * 2 ** (attempt - 1), pol["max_delay_s"])
            db.execute("UPDATE notifications SET status='PENDING', status_reason='transient error, retry scheduled', attempts=?, last_error=?, next_attempt_real=? WHERE id=?",
                       (attempt, err, now + delay, notif["id"]), conn)
        db.execute("INSERT INTO notification_attempts(notification_id,attempt_no,at_real,success,error) VALUES (?,?,?,0,?)", (notif["id"], attempt, now, err), conn)


def _create_and_send(conn, inc: dict, kind: str, recipients: list[str], policy: dict) -> dict:
    dedup = f"{inc['id']}:{kind}:{inc['severity']}" if kind in ("ALERT", "ESCALATION") else f"{inc['id']}:{kind}"
    existing = db.row("SELECT * FROM notifications WHERE dedup_key=?", (dedup,), conn)
    if existing:
        return {"kind": kind, "status": existing["status"], "duplicate": True, "id": existing["id"]}
    subject, text, html_body = compose(conn, inc, kind)
    now = db.now_real()
    storm = policy["storm"]
    status, reason = "PENDING", None
    if not recipients:
        status, reason = "SUPPRESSED", "no recipients configured (ALERT_RECIPIENTS)"
    else:
        sent_last_hour = db.scalar("SELECT COUNT(*) FROM notifications WHERE channel='EMAIL' AND status IN ('SENT','TEST_MODE','PENDING') AND created_real > ?",
                                   (now - 3600,), conn)
        recent_same = db.scalar("SELECT COUNT(*) FROM notifications WHERE incident_id=? AND channel='EMAIL' AND kind=? AND status IN ('SENT','TEST_MODE') AND created_real > ?",
                                (inc["id"], kind, now - storm["min_interval_same_incident_s"]), conn)
        if sent_last_hour >= storm["max_emails_per_hour"]:
            status, reason = "SUPPRESSED", f"storm protection: {sent_last_hour} emails in the last hour (max {storm['max_emails_per_hour']})"
        elif recent_same and kind == "ALERT":
            status, reason = "SUPPRESSED", "an alert for this incident was emailed less than an hour ago"
        elif inc["simulated"] and not policy.get("include_simulated", True):
            status, reason = "SUPPRESSED", "simulated incident (include_simulated=false)"
    cur = db.execute("""INSERT INTO notifications(incident_id,dedup_key,kind,severity,channel,recipients,subject,status,status_reason,created_real)
                        VALUES (?,?,?,?,'EMAIL',?,?,?,?,?)""",
                     (inc["id"], dedup, kind, inc["severity"], db.dumps([_mask(r) for r in recipients]), subject, status, reason, now), conn)
    notif = db.row("SELECT * FROM notifications WHERE id=?", (cur.lastrowid,), conn)
    if status == "PENDING":
        _deliver(conn, notif, subject, text, html_body, recipients)
    final = db.row("SELECT status, status_reason FROM notifications WHERE id=?", (notif["id"],), conn)
    inc_store.timeline(conn, inc["id"], "NOTIFICATION", "AGENT_4_NOTIFICATION", f"{kind} email: {final['status']}" + (f" ({final['status_reason']})" if final["status_reason"] else ""),
                       {"notificationId": notif["id"]}, clock.now(conn))
    return {"kind": kind, "status": final["status"], "reason": final["status_reason"], "id": notif["id"], "duplicate": False}


def _mask(addr: str) -> str:
    name, _, domain = addr.partition("@")
    return (name[:2] + "***@" + domain) if domain else "***"


def run(conn, iid: str, trigger: Trigger) -> dict:
    with agent_run(conn, "NOTIFICATION", iid, trigger) as h:
        policy = load_policy("notification")
        inc = db.row("SELECT * FROM incidents WHERE id=?", (iid,), conn)
        if inc is None:
            raise KeyError(iid)
        rule = policy["policy"][inc["severity"]]
        actions = []
        alerted = db.row("SELECT * FROM notifications WHERE incident_id=? AND kind IN ('ALERT','ESCALATION') AND channel='EMAIL' AND status IN ('SENT','TEST_MODE') ORDER BY id DESC LIMIT 1",
                         (iid,), conn)
        if inc["status"] in inc_store.OPEN_STATUSES:
            if rule["email"]:
                kind = "ALERT" if not alerted else ("ESCALATION" if inc_store.sev_rank(inc["severity"]) > inc_store.sev_rank(alerted["severity"]) else None)
                if kind:
                    actions.append(_create_and_send(conn, inc, kind, settings.alert_recipients, policy))
            dedup = f"{iid}:DASHBOARD:{inc['severity']}"
            if not db.row("SELECT id FROM notifications WHERE dedup_key=?", (dedup,), conn):
                db.execute("""INSERT INTO notifications(incident_id,dedup_key,kind,severity,channel,status,status_reason,created_real)
                              VALUES (?,?,'ALERT',?,'DASHBOARD','DASHBOARD_ONLY',?,?)""",
                           (iid, dedup, inc["severity"], f"policy for {inc['severity']}: channel {rule['channel']}, email={rule['email']}", db.now_real()), conn)
                actions.append({"kind": "DASHBOARD", "status": "DASHBOARD_ONLY"})
            if inc["status"] == "ACKNOWLEDGED" and alerted:
                actions.append(_create_and_send(conn, inc, "ACKNOWLEDGED", settings.alert_recipients, policy))
        elif inc["status"] in ("RESOLVED", "CLOSED") and alerted and policy.get("notify_on_resolution", True):
            actions.append(_create_and_send(conn, inc, "RESOLVED", settings.alert_recipients, policy))
        db.execute("UPDATE incidents SET processed_version=pipeline_version, claimed_by=NULL, claimed_real=NULL WHERE id=?", (iid,), conn)
        _advance(conn, inc, "NOTIFIED")
        h.summary = "; ".join(f"{a['kind']}:{a['status']}" for a in actions) or f"no notification required (policy {inc['severity']}: email={rule['email']})"
        h.details = {"actions": actions, "policy": rule}
        return {"incidentId": iid, "actions": actions, "policy": rule, "valid": True}


def process_retries(conn) -> int:
    """Retry due PENDING emails (called by the engine tick)."""
    due = db.rows("SELECT * FROM notifications WHERE status='PENDING' AND channel='EMAIL' AND next_attempt_real IS NOT NULL AND next_attempt_real <= ?",
                  (db.now_real(),), conn)
    for n in due:
        inc = db.row("SELECT * FROM incidents WHERE id=?", (n["incident_id"],), conn)
        subject, text, html_body = compose(conn, inc, n["kind"])
        recips = settings.escalation_recipients if n["kind"] == "ESCALATION" and settings.escalation_recipients else settings.alert_recipients
        _deliver(conn, n, subject, text, html_body, recips)
    return len(due)


def check_escalations(conn) -> int:
    """CRITICAL incidents not acknowledged within escalate_after_s (wall-clock) get one escalation email."""
    policy = load_policy("notification")
    after = policy["policy"]["CRITICAL"].get("escalate_after_s")
    if not after:
        return 0
    count = 0
    for inc in db.rows("SELECT * FROM incidents WHERE severity='CRITICAL' AND status IN ('OPEN','INVESTIGATING')", conn=conn):
        first = db.row("SELECT created_real FROM notifications WHERE incident_id=? AND kind='ALERT' AND channel='EMAIL' AND status IN ('SENT','TEST_MODE') ORDER BY id LIMIT 1",
                       (inc["id"],), conn)
        if first and db.now_real() - first["created_real"] >= after:
            if not db.row("SELECT id FROM notifications WHERE dedup_key=?", (f"{inc['id']}:ESCALATION:CRITICAL",), conn):
                recips = settings.escalation_recipients or settings.alert_recipients
                _create_and_send(conn, inc, "ESCALATION", recips, policy)
                count += 1
    return count
